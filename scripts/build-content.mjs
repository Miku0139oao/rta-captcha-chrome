// Builds the MV3 content script.
//
// Content scripts are classic scripts: an `import` statement is a syntax error,
// and Chrome silently drops the whole file when one is present. The source lives
// in src/content.js and imports the shared modules, so it has to be bundled into
// a single plain script before it can be loaded. The output is committed, which
// keeps "clone and load unpacked" working without a build step.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { bundleModule, readSource } from "./lib/bundle.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const protocol = bundleModule(
  await readSource(root, "lib", "protocol.js"),
  "lib/protocol.js",
  [],
);
const pageCore = bundleModule(
  await readSource(root, "lib", "page-core.js"),
  "lib/page-core.js",
  ["./protocol.js"],
);
const entry = bundleModule(
  await readSource(root, "src", "content.js"),
  "src/content.js",
  [
    "./lib/page-core.js",
    "./lib/protocol.js",
    "../lib/page-core.js",
    "../lib/protocol.js",
  ],
);

const banner = `// Code generated by scripts/build-content.js; DO NOT EDIT.
// Source: src/content.js, lib/page-core.js, lib/protocol.js
`;

const bundle = `${banner}
(function () {
  "use strict";
${protocol}
${pageCore}
${entry}})();
`.replace(/\r\n/g, "\n");

const outFile = path.join(root, "content.js");

if (process.argv.includes("--check")) {
  // CI uses this to prove the committed script still matches its sources, and to
  // guarantee it is a classic script that Chrome will actually load.
  const existing = await readFile(outFile, "utf8");
  if (existing !== bundle) {
    throw new Error(
      "content.js is out of date; run npm run build:content",
    );
  }
  console.log("content.js matches its sources.");
} else {
  await mkdir(path.dirname(outFile), { recursive: true });
  await writeFile(outFile, bundle, "utf8");
  console.log(`Wrote content.js (${bundle.length} bytes)`);
}
