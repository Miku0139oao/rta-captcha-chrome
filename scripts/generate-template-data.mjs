import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(SCRIPT_DIRECTORY, "..");
if (!process.argv[2]) {
  throw new Error(
    "usage: node scripts/generate-template-data.mjs <path-to-rta-sales-client-go>",
  );
}
const sourceRoot = path.resolve(process.argv[2]);

const sourceFiles = {
  learned: path.join(sourceRoot, "rtasales", "embedded_ocr_learned.go"),
  consensus: path.join(sourceRoot, "rtasales", "embedded_ocr_consensus_learned.go"),
};

const [learnedSource, consensusSource] = await Promise.all([
  readFile(sourceFiles.learned, "utf8"),
  readFile(sourceFiles.consensus, "utf8"),
]);

function extractGoTemplateMap(source, variableName) {
  const declaration = `var ${variableName} = map[byte][]string{`;
  const start = source.indexOf(declaration);
  if (start < 0) {
    throw new Error(`Cannot find ${variableName}`);
  }

  const result = {};
  const entryPattern = /'([0-9a-f])':\s*\{([\s\S]*?)\n\s*\},/g;
  entryPattern.lastIndex = start + declaration.length;
  for (let match = entryPattern.exec(source); match; match = entryPattern.exec(source)) {
    const values = [...match[2].matchAll(/"([A-Za-z0-9+/=]+)"/g)].map(
      (value) => value[1],
    );
    if (values.length === 0) {
      throw new Error(`No templates found for ${variableName}.${match[1]}`);
    }
    result[match[1]] = values;
    if (Object.keys(result).length === 16) {
      break;
    }
  }

  const alphabet = Object.keys(result).join("");
  if (alphabet !== "0123456789abcdef") {
    throw new Error(`${variableName} has unexpected alphabet ${alphabet}`);
  }
  return result;
}

const maps = {
  LEARNED_GLYPH_TEMPLATES: extractGoTemplateMap(
    learnedSource,
    "learnedGlyphTemplates",
  ),
  SUPPLEMENTAL_GLYPH_TEMPLATES: extractGoTemplateMap(
    consensusSource,
    "supplementalGlyphTemplates",
  ),
  FITTED_GLYPH_TEMPLATES: extractGoTemplateMap(
    consensusSource,
    "fittedGlyphTemplates",
  ),
};

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

const output = [
  "// Code generated by scripts/generate-template-data.mjs; DO NOT EDIT.",
  "// Ported from rta-sales-client-go's locally verified embedded OCR templates.",
  `// embedded_ocr_learned.go sha256: ${sha256(learnedSource)}`,
  `// embedded_ocr_consensus_learned.go sha256: ${sha256(consensusSource)}`,
  "",
  ...Object.entries(maps).flatMap(([name, value]) => [
    `export const ${name} = Object.freeze(${JSON.stringify(value)});`,
    "",
  ]),
].join("\n");

const outputPath = path.join(PROJECT_ROOT, "ocr", "templates.generated.js");
await writeFile(outputPath, output, "utf8");
console.log(`Generated ${path.relative(PROJECT_ROOT, outputPath)}`);
